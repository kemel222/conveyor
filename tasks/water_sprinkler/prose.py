def _commas(obj):
    if isinstance(obj, bool):
        return obj
    if isinstance(obj, float):
        return f"{obj:g}".replace(".", ",")
    if isinstance(obj, str):
        return re.sub(r"(?<=\d)\.(?=\d)(?!\d*\.\d)", ",", obj) if "13130" not in obj else obj
    if isinstance(obj, dict):
        return {k: _commas(v) for k, v in obj.items()}
    return obj


def prompt(d: dict, bibliography: list[str], keys=None, fix: dict[str, list[str]] | None = None,
           previous: dict | None = None) -> str:
    """keys – какие разделы написать; fix – замечания по этим разделам; previous – отклонённый текст."""
    keys = list(keys or SECTIONS)
    parts = ["Напиши разделы пояснительной записки контрольной работы. Верни JSON: для каждого ключа — массив абзацев. "
             "Объём в словах — жёсткое требование: текст короче минимума будет отклонён. Перед ответом посчитай "
             "слова в каждом разделе и целься в середину диапазона.", RULES, "РАЗДЕЛЫ:"]
    for key in keys:
        title, lo, hi, what = SECTIONS[key]
        parts.append(f"- {key}: «{title}», {lo}–{hi} слов (цель ≈{(lo + hi) // 2}). Раскрыть: {what}.")
    parts.append("ДАННЫЕ (единственный источник чисел; десятичный разделитель — запятая, пиши числа ровно так):\n"
                 + json.dumps(_commas(facts(d, bibliography)), ensure_ascii=False, indent=1))
    if fix:
        lines = ["ПРЕДЫДУЩИЙ ВАРИАНТ ЭТИХ РАЗДЕЛОВ ОТКЛОНЁН. Перепиши каждый раздел целиком, сохранив удачное "
                 "и дополнив содержанием по теме раздела:"]
        for key in keys:
            if key in fix:
                lines.append(f"- {key}: " + "; ".join(fix[key]))
        parts.append("\n".join(lines))
        if previous:
            parts.append("ОТКЛОНЁННЫЙ ТЕКСТ (для опоры):\n" +
                         json.dumps({k: previous.get(k, []) for k in keys}, ensure_ascii=False, indent=1))
    return "\n\n".join(parts)
